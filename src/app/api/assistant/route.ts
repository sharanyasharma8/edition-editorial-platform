import { NextResponse } from "next/server";
import { z } from "zod";
import { getSession } from "@/lib/auth";
import { consumeRateLimit } from "@/lib/cache";
import { isSameOriginRequest } from "@/lib/request-security";

const schema = z.object({
  title: z.string().trim().min(3).max(180),
  dek: z.string().max(500).optional(),
  body: z.string().max(30_000).optional(),
  brand: z.enum(["edit", "form"]),
  imageDescription: z.string().max(1_000).optional(),
  allowExternalProcessing: z.boolean().optional().default(false),
});

export async function POST(request: Request) {
  const session = await getSession();
  if (!session) return NextResponse.json({ error: "Authentication required." }, { status: 401 });
  if (!isSameOriginRequest(request)) return NextResponse.json({ error: "Cross-origin request is not allowed." }, { status: 403 });

  const limit = await consumeRateLimit(`assistant:${session.id}`, 20, 60 * 60);
  if (limit.unavailable) return NextResponse.json({ error: "Editorial assistant protection is temporarily unavailable." }, { status: 503 });
  if (!limit.allowed) {
    return NextResponse.json({ error: "The editorial assistant usage limit has been reached. Try again later." }, {
      status: 429,
      headers: { "Retry-After": String(limit.retryAfterSeconds) },
    });
  }

  const parsed = schema.safeParse(await request.json().catch(() => null));
  if (!parsed.success) return NextResponse.json({ error: "A valid headline and publication are required.", details: parsed.error.flatten() }, { status: 400 });
  const provider = (process.env.AI_PROVIDER || "demo").toLowerCase();
  const externalEnabled = process.env.AI_EXTERNAL_PROCESSING_ENABLED === "true";
  if (provider === "openai" && !externalEnabled) {
    return NextResponse.json({ error: "External AI processing is disabled by server policy. No draft text was sent to a provider." }, { status: 503 });
  }
  if (provider === "openai" && !parsed.data.allowExternalProcessing) {
    return NextResponse.json({ error: "Confirm that this draft is approved for external AI processing before continuing." }, { status: 400 });
  }
  const remote = process.env.AI_SERVICE_URL;
  if (provider === "openai" && !remote) {
    return NextResponse.json({ error: "The configured AI service is unavailable. No draft text was sent to a provider." }, { status: 503 });
  }
  if (remote) {
    try {
      const response = await fetch(`${remote}/v1/editorial/package`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          ...(process.env.AI_SERVICE_TOKEN ? { Authorization: `Bearer ${process.env.AI_SERVICE_TOKEN}` } : {}),
        },
        body: JSON.stringify({
          title: parsed.data.title,
          dek: parsed.data.dek || "",
          body: parsed.data.body || "",
          brand: parsed.data.brand,
          image_description: parsed.data.imageDescription || "",
          allow_external_processing: parsed.data.allowExternalProcessing,
        }),
        signal: AbortSignal.timeout(18_000),
      });
      if (response.ok) {
        const raw = await response.json();
        return NextResponse.json({
          mode: raw.mode,
          label: raw.label,
          headlineSuggestions: raw.headline_suggestions,
          summary: raw.summary,
          tags: raw.tags,
          seoDescription: raw.seo_description,
          altText: raw.alt_text,
          related: raw.related,
          requiresHumanApproval: raw.requires_human_approval,
          validationNotes: raw.validation_notes,
        });
      }
      if (provider === "openai") {
        return NextResponse.json({ error: "The external AI provider did not return a valid response. No demo substitution was made." }, { status: 502 });
      }
      console.warn(`[edition] AI service returned ${response.status}; using transparent local demo suggestions.`);
    } catch (error) {
      if (provider === "openai") {
        console.warn("[edition] Configured AI service unavailable.", error);
        return NextResponse.json({ error: "The external AI service is temporarily unavailable." }, { status: 503 });
      }
      console.warn("[edition] AI service unavailable; using transparent local demo suggestions.", error);
    }
  }

  const title = parsed.data.title;
  return NextResponse.json({
    mode: "demo",
    label: "Illustrative demo output — not generated by an LLM",
    headlineSuggestions: [`${title}: a closer look`, `Inside the ideas shaping ${title.toLowerCase()}`, `Why ${title.toLowerCase()} matters now`],
    summary: parsed.data.dek || `An editorial introduction exploring the context, people and ideas behind ${title.toLowerCase()}.`,
    tags: parsed.data.brand === "edit" ? ["Perspective", "Culture", "Style", "Ideas"] : ["Design", "Materials", "Architecture", "Ideas"],
    seoDescription: `Explore ${title.toLowerCase()} in this considered EDITION story. Reporting, perspective and ideas from ${parsed.data.brand === "edit" ? "THE EDIT" : "FORM"}.`.slice(0, 158),
    altText: parsed.data.imageDescription?.trim() || "Review the image and describe only the visible subject, setting, composition and meaningful details.",
    related: [],
    requiresHumanApproval: true,
  });
}
